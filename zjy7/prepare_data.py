def mk(user, assistant):
    return {"messages": [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": user},
        {"role": "assistant", "content": assistant}
    ]}

def parse_dialogue(fp):
    lines = Path(fp).read_text(encoding="utf-8").splitlines()
    ds = []
    for line in lines:
        line = line.strip()
        if not line: continue
        m = re.match(r'^([^：:]{1,10})[：:](.+)$', line)
        if m:
            ds.append({"role": m.group(1).strip(), "content": m.group(2).strip()})
        elif len(line) > 3 and not line.startswith('---'):
            ds.append({"role": "旁白", "content": line})
    return ds

def dialogue_samples(ds, target="爱莉希雅"):
    merged = []
    for d in ds:
        if merged and merged[-1]["role"] == d["role"]:
            merged[-1]["content"] += " " + d["content"]
        else:
            merged.append(d.copy())
    samples = []
    for i in range(len(merged)):
        if merged[i]["role"] != target or len(merged[i]["content"]) < 3: continue
        # 多轮上下文样本（增加上下文窗口）
        ctx = []
        for j in range(max(0, i - 5), i):
            if merged[j]["role"] != "旁白":
                ctx.append(f"{merged[j]['role']}：{merged[j]['content']}")
        user = "\n".join(ctx) if ctx else "（继续对话）"
        samples.append(mk(user, merged[i]["content"]))
    return samples

