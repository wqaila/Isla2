def _question_for(text):
    """给一句台词挑一个合适的 user 侧问题（加权打分）；挑不出返回 None。

    ⚠️ 这是**兜底**路径。只有约 40 个模板问句，是「提问坍缩」的根源 ——
    正常应当由 `gen_questions.py` 生成的多样化问法覆盖（见 load_question_cache）。
    """
    best_score = 0
    best_question = None
    for keywords, weight, question in MONO_RULES:
        if any(w in text for w in keywords):
            if weight > best_score:
                best_score = weight
                best_question = question
    if best_question is None:
        # 兜底：检查是否提到其他角色
        mentioned = [c for c in OTHER_CHARS if c in text]
        if mentioned:
            best_question = f"说说{random.choice(mentioned)}吧"
    return best_question


# ============ 生成的多样化提问（可选，但强烈建议）============
#
# `gen_questions.py` 用本地 LLM 给每条台词生成 3 个**不同**的用户提问，
# 落在 `question_cache.json`。有缓存就用它，一条台词出 3 个样本。
#
# 【为什么这是治本】模板问句总共只有约 40 种（MONO_RULES 27 + 「说说X吧」13），
# 实测 **80% 的训练样本都挤在这 40 个问句里** —— 模型对这几个问法特别顺，
# 换个说法就发懵。「削峰」（删掉高频问句的样本）只是治标：模型少见了同一个
# 问法，但**依然没见过其他问法**。生成式问法把种类从 40 涨到几千。
#
# 缓存缺失时自动退回模板问句 —— 不强制依赖，保证 prepare_data 单独也能跑。
_QUESTION_CACHE = None

# mono 路线的命中统计（按文件累积，最后汇总打印，避免刷屏）
_MONO_HIT = 0
_MONO_MISS = 0


def load_question_cache():
    """读 question_cache.json（只读一次，缓存在模块级）。"""
    global _QUESTION_CACHE
    if _QUESTION_CACHE is None:
        path = PROJECT_ROOT / "question_cache.json"
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            _QUESTION_CACHE = data.get("lines", {}) or {}
            logging.info(f"生成提问缓存：{len(_QUESTION_CACHE)} 句可用"
                         f"（模型 {data.get('meta', {}).get('model', '?')}）")
        except FileNotFoundError:
            _QUESTION_CACHE = {}
            logging.warning("没有 question_cache.json —— 将退回约 40 个模板问句，"
                            "提问会严重坍缩。建议先跑：python gen_questions.py")
        except Exception as e:
            _QUESTION_CACHE = {}
            logging.warning(f"question_cache.json 读取失败（{e}），退回模板问句")
    return _QUESTION_CACHE


def load_general_data():
    """读 `general_data.json` —— 防灾难性遗忘用的通用指令数据。

    【为什么需要】训练集几乎全是角色数据时，纯角色微调会让模型
    「问啥都往角色上拐」：常识问题、写作、讲道理全用角色语气糊过去，
    基础指令跟随能力退化。混入 10~30% 通用数据能显著缓解。

    由 `gen_general.py` 生成。文件缺失时返回空列表（只告警不报错）。
    """
    path = PROJECT_ROOT / "general_data.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return []
    except Exception as e:
        logging.warning(f"general_data.json 读取失败（{e}），跳过通用数据")
        return []
    out = []
    for item in data.get("pairs", []) or []:
        if isinstance(item, (list, tuple)) and len(item) >= 2:
            q, a = str(item[0]).strip(), str(item[1]).strip()
            if not q or not a:
                continue
            # ⚠️ 通用答案也要过**长度红线** —— 否则会出现超 200 字的样本，
            #    和我们给角色数据定的「绝对禁止超过 200 字」自相矛盾
            #    （实测漏这一步会混进 283 字的样本）。
            for piece in split_long_text(a):
                out.append(mk(q, piece))
    return out


def mono_samples(sentences):
    cache = load_question_cache()
    samples = []
    global _MONO_HIT, _MONO_MISS
    for raw in sentences:
        # ⚠️ 先切超长再配问题：OCR 会把整屏文字连成一行（实测有 7541 字的），
        # 那种长度既违反角色卡上限、又会被 max_seq_length 截断。
        # 问题按**片段自身**重新匹配 —— 否则切开后可能问不对题。
        for s in split_long_text(raw):
            questions = cache.get(s)
            if questions:
                _MONO_HIT += 1
                for q in questions:
                    samples.append(mk(q, s))
                continue
            # 回退：模板问句
            q = _question_for(s)
            if q is None:
                continue
            _MONO_MISS += 1
            samples.append(mk(q, s))
    return samples

# ============ 数据质量校验 ============
def _last_assistant(msgs):
    """取最后一条 assistant 消息的内容（多轮样本的「要学的回复」）。"""
    for m in reversed(msgs):
        if m["role"] == "assistant":
            return m["content"]
    return ""


def validate_samples(samples):
    """自检样本结构。

    ⚠️ 不能假设样本是固定的三轮 `system/user/assistant` ——
    对话型语料会产出**真正的多轮**样本（`system/user/assistant/user/…/assistant`）。
    旧版硬断言 `len(msgs) != 3` 并把长度检查写死成 `msgs[2]`，
    加了多轮数据之后会把每一条都误报成「消息数不是3」+「回复过短」。
    """
    issues = []
    seen = set()
    for i, s in enumerate(samples):
        msgs = s["messages"]
        # 结构：system 开头，最后一条必须是 assistant，且 user/assistant 交替
        if msgs[0]["role"] != "system":
            issues.append(f"样本 {i}: 首条不是 system")
            continue
        if msgs[-1]["role"] != "assistant":
            issues.append(f"样本 {i}: 末条不是 assistant")
            continue
        body = msgs[1:]
        expect = "user"
        for m in body:
            if m["role"] != expect:
                issues.append(f"样本 {i}: 角色未交替（期望 {expect}，实际 {m['role']}）")
                break
            expect = "assistant" if expect == "user" else "user"

        reply = _last_assistant(msgs)
        if len(reply) < 2:
            issues.append(f"样本 {i}: assistant 回复过短")
        # 每个 user 轮都要有内容
        if any(not m["content"].strip() for m in body if m["role"] == "user"):
            issues.append(f"样本 {i}: 有空的 user 输入")
        if "爱莉希雅" not in msgs[0]["content"]:
            issues.append(f"样本 {i}: system 中缺少角色名")

        # 重复：按「最后一条 user + 最后一条 assistant」判重
        last_user = next((m["content"] for m in reversed(body)
                          if m["role"] == "user"), "")
        key = (last_user, reply)
        if key in seen:
            issues.append(f"样本 {i}: 重复样本 (user={last_user[:30]})")
        seen.add(key)
    return issues

# ============ 长度分布报告 ============

# 分桶对齐角色卡的长度约束，便于一眼看出分布是否合规
_LEN_BUCKETS = [
    (0, 5, "  碎片(<5)"),
    (5, 15, "  偏短(5-14)"),
    (15, 31, "  合规·简单(15-30)"),
    (31, 61, "  合规·日常(31-60)"),
    (61, 121, "  合规·复杂(61-120)"),
    (121, 201, "  边缘(121-200)"),
    (201, 10 ** 9, "  ⚠️ 违规(>200)"),
]


def _report_lengths(samples):
    """打印 assistant 侧长度分布。

    为什么要专门打这个：角色卡写死了「绝对禁止超过 200 字」，
    而训练集里的长度分布才是模型实际学到的东西 ——
    两者不一致时，模型会按训练集的习惯写，把角色卡的规则架空。
    """
    # ⚠️ 用**最后一条 assistant**，不能用写死的 messages[2] ——
    #    多轮样本里 index 2 是 user 轮，会量出错误长度并误报超限。
    lens = [len(_last_assistant(s["messages"])) for s in samples]
    if not lens:
        return
    total = len(lens)
    logging.info("assistant 长度分布（角色卡上限 %d 字）：" % MAX_ASSISTANT_LEN)
    for lo, hi, name in _LEN_BUCKETS:
        n = sum(1 for x in lens if lo <= x < hi)
        if n:
            logging.info(f"{name:<18} {n:5} 条 ({n / total * 100:5.1f}%)")
    over = [x for x in lens if x > MAX_ASSISTANT_LEN]
    logging.info(f"  最长 {max(lens)} 字 / 中位 {sorted(lens)[total // 2]} 字"
                 + (f"  ⚠️ 仍有 {len(over)} 条超上限" if over else "  ✅ 无超限样本"))


def main():
    # 统一随机种子，保证数据打乱顺序可复现（必须在任何 random 调用之前设置）
    random.seed(42)
    cfg = load_config()
    raw_dir = resolve_path(cfg["data"]["raw_data_dir"])
    out_path = resolve_path(cfg["data"]["data_path"])

    # 长度上限可由配置覆盖。
    # 角色卡里有两个数：**软上限 120**（「复杂问题/讲故事最多120字」）
    # 与**硬上限 200**（「绝对禁止超过200字」）。
    # 默认取硬上限 200 —— 对齐角色卡的绝对规则；
    # 想更严（把软上限也守住）就在 train_config.json 里设
    # `"data": { "max_assistant_len": 120 }`。
    global MAX_ASSISTANT_LEN
    MAX_ASSISTANT_LEN = int(cfg["data"].get("max_assistant_len", MAX_ASSISTANT_LEN))
    logging.info(f"assistant 长度上限: {MAX_ASSISTANT_LEN} 字"
                 f"（train_config.json 的 data.max_assistant_len）")

    # 人设来自哪里必须留痕：训练数据一旦生成，就分不清用的是哪份人设了
    logging.info(f"人设来源: {SYSTEM_SOURCE}")
    if "兜底" in SYSTEM_SOURCE:
        logging.error("用的是内置兜底人设，与线上可能不一致 —— 先修好角色卡再训练！")

    all_samples = []

    # 知识库 + 同义提问 + 重复关键 Q&A
    for cat, items in KB.items():
        for q, a in items:
            all_samples.append(mk(q, a))

    logging.info(f"知识库: {sum(len(v) for v in KB.values())} 条")

    # 同义提问变体
    synonym_count = 0
    for cat, items in KB.items():
        for q, a in items:
            if q in SYNONYM_QUESTIONS:
                for alt_q in SYNONYM_QUESTIONS[q]:
                    all_samples.append(mk(alt_q, a))
                    synonym_count += 1
    logging.info(f"同义提问变体: {synonym_count} 条")

    # 重复高频关键 Q&A
    repeat_count = 0
    for cat, items in KB.items():
        for q, a in items:
            if q in KEY_QA_REPEAT:
                for _ in range(KEY_QA_REPEAT[q]):
                    all_samples.append(mk(q, a))
                    repeat_count += 1
    logging.info(f"重复关键 Q&A: {repeat_count} 条")

    # 拒答样本
    for q, a in REJECTION_SAMPLES:
        all_samples.append(mk(q, a))
    logging.info(f"拒答/角色保护样本: {len(REJECTION_SAMPLES)} 条")

    # 文件处理
    downloads_dir = raw_dir
    if not downloads_dir.exists():
        logging.error(f"数据目录不存在: {downloads_dir}")
        return

    for fp in sorted(downloads_dir.glob("*.txt")):
        ds = parse_dialogue(fp)
        role_lines = [d for d in ds if d["role"] != "旁白"]
        is_dialogue = len(set(d["role"] for d in role_lines if d["role"] != "旁白")) >= 2

        if is_dialogue:
            s = dialogue_samples(ds)
        else:
            sentences = [d["content"] for d in ds if len(d["content"]) >= 2]
            s = mono_samples(sentences)
        logging.info(f"  {fp.name}: {len(s)} 样本")
        all_samples.extend(s)

    logging.info(f"mono 路线：{_MONO_HIT} 句用生成问法、{_MONO_MISS} 句用模板问句")

    # ---- 混入通用指令数据（防灾难性遗忘）----
    #
    # ⚠️ 这里刻意**沿用同一个角色 system**（`mk()` 用的就是 SYSTEM），
    #    而不是换成「你是一个有用的助手」。理由：线上推理时 system 永远是
    #    角色卡，所以模型必须在**人设之下**也能把通用问题答对 ——
    #    要治的是「问啥都往角色上拐、拿角色语气把常识问题糊过去」，
    #    不是教它「换个身份时该怎么答」（那种场景根本不会出现）。
    ratio = float(cfg["data"].get("general_data_ratio", 0.0) or 0.0)
    if ratio > 0:
        pool = load_general_data()
        if pool:
            # 目标：general / (character + general) = ratio
            need = int(len(all_samples) * ratio / (1 - ratio))
            take = min(need, len(pool))
            all_samples.extend(random.sample(pool, take))
            logging.info(
                f"混入通用指令数据：{take} 条（池子 {len(pool)} 条）"
                f"→ 占比 {take / len(all_samples) * 100:.1f}%（目标 {ratio * 100:.0f}%）")
        else:
            logging.warning("配了 general_data_ratio 但没有 general_data.json —— "
                            "先跑 python gen_general.py，否则有灾难性遗忘风险")

    # 质量校验
    issues = validate_samples(all_samples)
    if issues:
        logging.warning(f"发现 {len(issues)} 个质量问题:")
        for issue in issues[:10]:
            logging.warning(f"  {issue}")
        if len(issues) > 10:
            logging.warning(f"  ... 还有 {len(issues) - 10} 个")

    # 长度分布报告 —— 角色卡的长度约束就是靠这里肉眼核对的
    _report_lengths(all_samples)

    # 打乱并保存
    random.shuffle(all_samples)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(all_samples, f, ensure_ascii=False, indent=2)

    logging.info(f"总计: {len(all_samples)} 样本 → {out_path}")

if __name__ == "__main__":
    main()