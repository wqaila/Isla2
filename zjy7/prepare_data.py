# ============ 长度红线（对齐角色卡）============
#
# 角色卡（zjy9 线上实际用的那份）写死了长度约束：
#   普通问候/简单问题 15-30 字 / 日常聊天 30-60 字 / 复杂问题最多 120 字
#   **绝对禁止超过 200 字**
#
# 训练集里若有远超上限的样本，等于在教模型「写长」——和角色卡直接打架。
# 更糟的是超过 `max_seq_length`（1024 token）的样本会在训练时被**截断**，
# 相当于教它「话说一半就停」。
#
# 实测：downloads/ 里存在 7541 字的「一行」（OCR 把整屏文字连成一行），
# 被 MONO_RULES 匹配后原样变成一条训练样本。这类必须在生成阶段切开。
MAX_ASSISTANT_LEN = 200

# 句末标点（中英文都收）——切长句时在这些位置断开
_SENT_END = "。！？!?…；;"


def split_long_text(text, limit=None, min_piece=4):
    """把过长文本按句末标点切分，返回若干不超过 limit 的片段（**已去重**）。

    - 不超限的**原样返回单元素列表**（不改变既有行为）
    - 单句本身就超长的**直接丢弃**（不做硬切，见下）
    - 过短碎片（< min_piece）丢弃 —— 长度红线的下限同样要守

    :param limit: 长度上限；``None`` 表示用当前的 :data:`MAX_ASSISTANT_LEN`
                  （该值可由 train_config.json 的 ``data.max_assistant_len`` 覆盖，
                  所以这里在**调用时**读取，而不是在定义时绑成默认参数）。

    ⚠️ **为什么要在这里去重**：这类超长 blob 基本是 OCR 把整屏文字连成一行
    的产物，而且**含大量重复**。实测本项目最长的一条（7541 字）里，
    139 句只有 36 句是唯一的，最高频的一句重复了 17 次。
    如果只切不去重，就会把「同一个问题」放大上百倍，
    等于亲手制造提问坍缩（本来就是要修的问题）。

    设计取舍：**宁可切碎、也不丢整条**。切出来的片段各自成样本，
    上下文（user 侧）沿用同一份，信息不浪费；实在切不动才丢。
    """
    if limit is None:
        limit = MAX_ASSISTANT_LEN
    text = (text or "").strip()
    if not text:
        return []
    if len(text) <= limit:
        return [text] if len(text) >= min_piece else []

    # 1) 先按句末标点切
    pieces, buf = [], ""
    for ch in text:
        buf += ch
        if ch in _SENT_END:
            pieces.append(buf.strip())
            buf = ""
    if buf.strip():
        pieces.append(buf.strip())

    # 2) 单句本身就超长的：**直接丢弃**，不做硬切。
    #
    #    为什么不像原来那样按长度硬切：硬切产生的是「半句话」样本
    #    （实测切出来的是 `…和温顺的一面, 嗯,那肯定是因为,你还没` 这种），
    #    等于教模型「话说到一半停住」—— 和长度红线的初衷正好相反。
    #    而且真实台词里不存在 200 字不带标点的句子，这类基本就是
    #    OCR 把整屏文字连成一行的产物，丢掉比切碎更干净。
    dropped = 0
    kept = []
    for p in pieces:
        if len(p) > limit:
            dropped += 1
            continue
        kept.append(p)
    if dropped:
        logging.debug(f"丢弃 {dropped} 段超长单句（>{limit} 字，无标点可切）")

    # 3) 丢碎片 + 段内去重（保持原顺序）
    seen, uniq = set(), []
    for p in kept:
        if len(p) < min_piece or p in seen:
            continue
        seen.add(p)
        uniq.append(p)
    return uniq


def parse_dialogue(fp):
    lines = Path(fp).read_text(encoding="utf-8").splitlines()
    ds = []
    for line in lines:
        line = line.strip()
        if not line: continue
        m = re.match(r'^([^：:]{1,10})[：:](.+)$', line)
        if m:
            ds.append({"role": m.group(1).strip(), "content": m.group(2).strip()})
        elif len(line) > 3 and not line.startswith('---'):
            ds.append({"role": "旁白", "content": line})
    return ds
# 多轮样本最多往回取几轮上下文。
# 线上（zjy9）默认带 20 条历史；这里取 8 是为了在 max_seq_length=1024 下
# 还能放下 system 人设 + 上下文（20 轮会逼近上限）。
_MAX_CTX_TURNS = 8

# 游戏 UI 伪台词（「（选项：…」「(继续)」等），不是角色说的话
_UI_ARTIFACT = re.compile(r"^[（(]")


def dialogue_samples(ds, target="爱莉希雅", max_ctx_turns=None):
    """把对话型语料转成**真正的多轮**样本。

    【为什么旧实现不行】
    旧版把上下文**拍平成一个字符串**塞进 user 字段：
        user = "爱莉希雅：…\\n芽衣：…\\n爱莉希雅：…"
    模型学到的是「看到一段带角色名的文字就接话」。但线上（zjy9）喂的是
    **真正的多轮 messages**（默认带 20 条历史）—— **训练/推理形态不匹配**，
    这是长对话里人设崩的主因。

    【新实现】按轮次切窗，组成标准的
        system / user / assistant / user / … / assistant
    结构，让模型训练时就见到和推理时一样的形状。

    【为什么 user 侧不带「角色：」前缀】
    线上 user 侧永远是玩家（舰长），所以把「对方说的话」统一映射成 user。
    保留前缀的话，模型可能学着在自己的回复里也带前缀。
    多说话人场景（`2.txt` 里有 7 个说话人）会把连续的 user 轮**合并**，
    保证严格交替。

    ⚠️ 依赖 `train_lora.py` 的 loss 掩码不变量（prompt 必须是 full 的严格前缀）——
    这条已在 2026-09-30 修好（`msgs[:last_asst]`）。**先修掩码再加多轮数据**，
    否则中间轮次的标签会错位。
    """
    if max_ctx_turns is None:
        max_ctx_turns = _MAX_CTX_TURNS

    # 1) 去掉旁白与游戏 UI 伪台词，然后合并相邻同角色行
    merged = []
    for d in ds:
        role = d["role"]
        if role == "旁白" or _UI_ARTIFACT.match(d["content"].strip()):
            continue
        if merged and merged[-1]["role"] == role:
            merged[-1]["content"] += " " + d["content"]
        else:
            merged.append({"role": role, "content": d["content"]})

    samples = []
    for i, turn in enumerate(merged):
        if turn["role"] != target:
            continue

        # 2) 往回找上下文窗口；起点若是 target 就后挪一轮，保证以 user 开头
        start = max(0, i - max_ctx_turns)
        if merged[start]["role"] == target:
            start += 1
        if start >= i:
            continue          # 没有上下文 → 退化成单轮，交给 mono 路线

        # 3) 组 messages；连续同角色合并，保证严格交替
        msgs = [{"role": "system", "content": SYSTEM}]
        for w in merged[start:i]:
            role = "assistant" if w["role"] == target else "user"
            if msgs[-1]["role"] == role:
                msgs[-1]["content"] += "\n" + w["content"]
            else:
                msgs.append({"role": role, "content": w["content"]})

        # 4) 目标台词按长度红线切开，每个片段各出一条样本
        #    （浅拷贝前缀，避免多个样本共享同一批 dict）
        for piece in split_long_text(turn["content"]):
            prefix = [dict(m) for m in msgs]
            samples.append({"messages": prefix + [
                {"role": "assistant", "content": piece}]})
    return samples

