def mono_samples(sentences):
    samples = []
    for s in sentences:
        # 加权打分：找出得分最高的规则
        best_score = 0
        best_question = None
        for keywords, weight, question in MONO_RULES:
            if any(w in s for w in keywords):
                if weight > best_score:
                    best_score = weight
                    best_question = question
        if best_question is None:
            # 兜底：检查是否提到其他角色
            mentioned = [c for c in OTHER_CHARS if c in s]
            if mentioned:
                best_question = f"说说{random.choice(mentioned)}吧"
            else:
                continue  # 无匹配的台词跳过
        samples.append(mk(best_question, s))
    return samples

# ============ 数据质量校验 ============
def validate_samples(samples):
    issues = []
    seen = set()
    for i, s in enumerate(samples):
        msgs = s["messages"]
        # 检查结构
        if len(msgs) != 3:
            issues.append(f"样本 {i}: 消息数不是3")
            continue
        if msgs[0]["role"] != "system" or msgs[1]["role"] != "user" or msgs[2]["role"] != "assistant":
            issues.append(f"样本 {i}: 角色顺序错误")
        # 检查内容长度
        if len(msgs[2]["content"]) < 2:
            issues.append(f"样本 {i}: assistant 回复过短")
        if len(msgs[1]["content"]) < 1:
            issues.append(f"样本 {i}: user 输入为空")
        # 检查是否包含 system prompt
        if "爱莉希雅" not in msgs[0]["content"]:
            issues.append(f"样本 {i}: system 中缺少角色名")
        # 检查重复
        key = (msgs[1]["content"], msgs[2]["content"])
        if key in seen:
            issues.append(f"样本 {i}: 重复样本 (user={msgs[1]['content'][:30]})")
        seen.add(key)
    return issues

def main():
    # 统一随机种子，保证数据打乱顺序可复现（必须在任何 random 调用之前设置）
    random.seed(42)
    cfg = load_config()
    raw_dir = resolve_path(cfg["data"]["raw_data_dir"])
    out_path = resolve_path(cfg["data"]["data_path"])

    all_samples = []

    # 知识库 + 同义提问 + 重复关键 Q&A
    for cat, items in KB.items():
        for q, a in items:
            all_samples.append(mk(q, a))

    logging.info(f"知识库: {sum(len(v) for v in KB.values())} 条")

    # 同义提问变体
    synonym_count = 0
    for cat, items in KB.items():
        for q, a in items:
            if q in SYNONYM_QUESTIONS:
                for alt_q in SYNONYM_QUESTIONS[q]:
                    all_samples.append(mk(alt_q, a))
                    synonym_count += 1
    logging.info(f"同义提问变体: {synonym_count} 条")

    # 重复高频关键 Q&A
    repeat_count = 0
    for cat, items in KB.items():
        for q, a in items:
            if q in KEY_QA_REPEAT:
                for _ in range(KEY_QA_REPEAT[q]):
                    all_samples.append(mk(q, a))
                    repeat_count += 1
    logging.info(f"重复关键 Q&A: {repeat_count} 条")

    # 拒答样本
    for q, a in REJECTION_SAMPLES:
        all_samples.append(mk(q, a))
    logging.info(f"拒答/角色保护样本: {len(REJECTION_SAMPLES)} 条")

    # 文件处理
    downloads_dir = raw_dir
    if not downloads_dir.exists():
        logging.error(f"数据目录不存在: {downloads_dir}")
        return

    for fp in sorted(downloads_dir.glob("*.txt")):
        ds = parse_dialogue(fp)
        role_lines = [d for d in ds if d["role"] != "旁白"]
        is_dialogue = len(set(d["role"] for d in role_lines if d["role"] != "旁白")) >= 2

        if is_dialogue:
            s = dialogue_samples(ds)
        else:
            sentences = [d["content"] for d in ds if len(d["content"]) >= 2]
            s = mono_samples(sentences)
        logging.info(f"  {fp.name}: {len(s)} 样本")
        all_samples.extend(s)

    # 质量校验
    issues = validate_samples(all_samples)
    if issues:
        logging.warning(f"发现 {len(issues)} 个质量问题:")
        for issue in issues[:10]:
            logging.warning(f"  {issue}")
        if len(issues) > 10:
            logging.warning(f"  ... 还有 {len(issues) - 10} 个")

    # 打乱并保存
    random.shuffle(all_samples)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(all_samples, f, ensure_ascii=False, indent=2)

    logging.info(f"总计: {len(all_samples)} 样本 → {out_path}")

if __name__ == "__main__":
    main()